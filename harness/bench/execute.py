"""Drive one case through all three analyzers and classify the outcome."""

from __future__ import annotations

import json
import os
from dataclasses import dataclass

from . import adapters, case as case_mod, classify as classify_mod
from .runner import ROOT, Runner

TOOL_TIMEOUT = int(os.environ.get("BENCH_TOOL_TIMEOUT", "300"))


@dataclass
class ToolSpec:
    name: str
    binary: str          # repository-relative path of the analyzer
    needs_php: bool


TOOLS = (
    ToolSpec("phpstan", "tools/bin/phpstan.phar", True),
    ToolSpec("psalm", "tools/bin/psalm.phar", True),
    ToolSpec("mago", "tools/bin/mago", False),
)


def ensure_psalm_config(case: case_mod.Case) -> str:
    """Psalm refuses to run without a config; generate a neutral one if absent."""
    local = case.abs_path("psalm.xml")
    if os.path.exists(local):
        return local
    generated_dir = case.abs_path(".generated")
    os.makedirs(generated_dir, exist_ok=True)
    generated = os.path.join(generated_dir, "psalm.xml")
    directories = "\n".join(f'        <directory name="{target}" />' for target in case.target_dirs)
    with open(generated, "w", encoding="utf-8") as handle:
        handle.write(
            '<?xml version="1.0"?>\n'
            '<psalm errorLevel="1" resolveFromConfigFile="true" '
            'findUnusedBaselineEntry="false" findUnusedCode="false" '
            'cacheDirectory=".generated/psalm-cache">\n'
            "    <projectFiles>\n"
            f"{directories}\n"
            "    </projectFiles>\n"
            "</psalm>\n"
        )
    return generated


def ensure_autoload(case: case_mod.Case) -> None:
    """Make sure the case has a Composer autoloader.

    Psalm refuses to start without one. Cases without third-party dependencies
    get a generated autoloader; cases with dependencies run a real install.
    """
    autoload = case.abs_path("vendor/autoload.php")
    if os.path.exists(autoload):
        return
    os.makedirs(case.abs_path("vendor"), exist_ok=True)
    directories = sorted({os.path.dirname(target) or "." for target in case.target_dirs})
    includes = "\n".join(
        f"foreach (glob(__DIR__ . '/../{directory}/*.php') ?: [] as $file) {{\n"
        f"    require_once $file;\n"
        f"}}" for directory in directories
    )
    with open(autoload, "w", encoding="utf-8") as handle:
        handle.write(
            "<?php\n\n"
            "// Generated by the harness: the case has no installed dependencies, but\n"
            "// Psalm requires a Composer autoloader to be present in the project root.\n"
            "// Delete this file (or set composer.install in case.json) to use real\n"
            "// dependencies instead.\n\n"
            f"{includes}\n"
        )


def build_argv(case: case_mod.Case, spec: ToolSpec) -> list[str]:
    """Full argv for one analyzer, with host paths.

    An analyzer can be swapped for a specific run with an environment override,
    which is how a drift check tries a newer release without touching the pins:
    ``BENCH_TOOL_PHPSTAN=/path/to/phpstan.phar``.
    """
    override = os.environ.get(f"BENCH_TOOL_{spec.name.upper()}")
    binary = override or os.path.join(ROOT, spec.binary)
    targets = [case.abs_path(target) for target in case.target_dirs]
    if spec.name == "phpstan":
        argv = [binary, "analyse", "--no-progress", "--error-format=json",
                f"--level={case.phpstan_level}"]
        config = case.abs_path("phpstan.neon")
        if os.path.exists(config):
            argv += ["-c", config]
        autoload = case.abs_path("vendor/autoload.php")
        if os.path.exists(autoload):
            argv += ["--autoload-file", autoload]
        return argv + targets
    if spec.name == "psalm":
        return [binary, "--no-cache", "--no-progress", "--output-format=json",
                f"--root={case.path}", f"--config={ensure_psalm_config(case)}"] + targets
    if spec.name == "mago":
        return [binary, "analyze", "--reporting-format", "json",
                "--reporting-target", "stdout"] + targets
    raise ValueError(f"unknown tool {spec.name}")


def _runtime_args(argv: list[str], runner: Runner) -> list[str]:
    """Translate host paths inside an argv into container paths where needed."""
    if runner.mode != "docker":
        return argv
    translated = []
    for item in argv:
        head, sep, tail = item.partition("=")
        if sep and tail.startswith("/"):
            translated.append(f"{head}={runner.runtime_path(tail)}")
        elif item.startswith("/"):
            translated.append(runner.runtime_path(item))
        else:
            translated.append(item)
    return translated


def run_tool(case: case_mod.Case, spec: ToolSpec, runner: Runner,
             php_version: str | None = None) -> tuple[dict, dict]:
    argv = _runtime_args(build_argv(case, spec), runner)
    if spec.needs_php:
        output = runner.php(argv, cwd=case.path, timeout=TOOL_TIMEOUT)
    else:
        output = runner.exec(argv, cwd=case.path, timeout=TOOL_TIMEOUT)
    parsed = adapters.ADAPTERS[spec.name](output["stdout"], output["stderr"])
    parsed.update({
        "exit_code": output["exit_code"],
        "duration_s": output["duration_s"],
    })
    result = classify_mod.classify(case, spec.name, parsed, php_version)
    evidence = {
        "case": case.id,
        "tool": spec.name,
        "argv": argv,
        "cwd": case.path,
        "exit_code": output["exit_code"],
        "duration_s": output["duration_s"],
        "stdout": output["stdout"],
        "stderr": output["stderr"],
        "diagnostics": parsed.get("diagnostics", []),
        "tool_error": parsed.get("tool_error"),
        "verdict": result["verdict"],
    }
    return result, evidence


def run_runtime_proof(case: case_mod.Case, runner: Runner, php_version=None) -> dict | None:
    script = case.runtime_script
    if not script:
        return None
    output = runner.php([runner.runtime_path(case.abs_path(script))], cwd=case.path, timeout=120)
    return {
        "script": script,
        "exit_code": output["exit_code"],
        "stdout": output["stdout"],
        "stderr": output["stderr"],
        "confirmed": output["exit_code"] == 0,
    }


def run_case(case: case_mod.Case, runner: Runner, tools=None, php_version=None,
             run_dir: str | None = None) -> dict:
    selected = [spec for spec in TOOLS if not tools or spec.name in tools]
    record = {"case": case.id, "domain": case.domain, "rule_class": case.rule_class,
              "basis": case.data.get("ground_truth", {}).get("basis"),
              "path": os.path.relpath(case.path, ROOT), "results": {}}

    if not case.diagnostics:
        ensure_autoload(case)

    # The runtime proof runs first: a case whose own proof fails cannot judge a
    # tool, so the tools are not run at all and every verdict is case_error.
    proof_failed = None
    if case.runtime_script:
        proof = run_runtime_proof(case, runner, php_version)
        record["runtime_proof"] = proof
        if run_dir:
            target = os.path.join(run_dir, "raw", case.id, "runtime.json")
            os.makedirs(os.path.dirname(target), exist_ok=True)
            with open(target, "w", encoding="utf-8") as handle:
                json.dump(proof, handle, indent=2)
        if not proof["confirmed"]:
            proof_failed = (f"runtime proof {proof['script']} exited {proof['exit_code']}: "
                            f"{(proof['stderr'] or proof['stdout']).strip()[:200]}")

    for spec in selected:
        if proof_failed or case.diagnostics:
            result = {
                "case": case.id, "tool": spec.name, "verdict": "case_error",
                "detail": proof_failed or "; ".join(case.diagnostics),
                "missing": [], "unexpected": [], "acknowledged": [], "diagnostics": [],
            }
        else:
            result, evidence = run_tool(case, spec, runner, php_version)
            if run_dir:
                target = os.path.join(run_dir, "raw", case.id, f"{spec.name}.json")
                os.makedirs(os.path.dirname(target), exist_ok=True)
                with open(target, "w", encoding="utf-8") as handle:
                    json.dump(evidence, handle, indent=2)
        record["results"][spec.name] = result
    return record
